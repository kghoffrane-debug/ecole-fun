-- 1) Les écoles
CREATE TABLE IF NOT EXISTS schools (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255) NOT NULL,
    status           VARCHAR(255) NOT NULL DEFAULT 'TRIAL',   -- TRIAL, ACTIVE, SUSPENDED
    plan             VARCHAR(255) NOT NULL DEFAULT 'basic',
    subscription_end DATE,
    deleted          BOOLEAN NOT NULL DEFAULT FALSE
);

-- 2) Les comptes (school_id vide = propriétaire du SaaS)
CREATE TABLE IF NOT EXISTS app_user (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT REFERENCES schools(id),
    username  VARCHAR(255) NOT NULL UNIQUE,     -- unique dans TOUTE la base (règle n°8 du cahier)
    password  VARCHAR(255) NOT NULL,            -- toujours haché (BCrypt)
    full_name VARCHAR(255),
    email     VARCHAR(255),
    role      VARCHAR(255),                     -- SUPER_ADMIN, ADMIN, TEACHER, PARENT, STUDENT, ACCOUNTANT
    deleted   BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_app_user_school ON app_user(school_id);

-- 3) Les classes
CREATE TABLE IF NOT EXISTS school_class (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id       BIGINT NOT NULL REFERENCES schools(id),
    level           VARCHAR(255),
    section         VARCHAR(255),
    capacity        INTEGER NOT NULL DEFAULT 25,
    annee_scolaire  VARCHAR(255),
    teacher_id      BIGINT REFERENCES app_user(id),
    deleted         BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_school_class_school ON school_class(school_id);

-- 4) Les matières
CREATE TABLE IF NOT EXISTS subject (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id   BIGINT NOT NULL REFERENCES schools(id),
    name        VARCHAR(255),
    coefficient DOUBLE PRECISION NOT NULL DEFAULT 1,
    level       VARCHAR(255),
    teacher_id  BIGINT REFERENCES app_user(id),
    deleted     BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_subject_school ON subject(school_id);

-- 5) Les élèves
CREATE TABLE IF NOT EXISTS student (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id       BIGINT NOT NULL REFERENCES schools(id),
    first_name      VARCHAR(255),
    last_name       VARCHAR(255),
    birth_date      DATE,
    avatar          VARCHAR(255),
    parent_id       BIGINT REFERENCES app_user(id),
    user_id         BIGINT REFERENCES app_user(id),
    school_class_id BIGINT REFERENCES school_class(id),
    annee_scolaire  VARCHAR(255),
    tuition_due     NUMERIC(12,2),
    medical_notes   VARCHAR(1000),
    deleted         BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_student_school ON student(school_id);

-- 6) Les notes
CREATE TABLE IF NOT EXISTS grade (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id      BIGINT NOT NULL REFERENCES schools(id),
    student_id     BIGINT NOT NULL REFERENCES student(id),
    subject_id     BIGINT NOT NULL REFERENCES subject(id),
    title          VARCHAR(255),
    score          DOUBLE PRECISION NOT NULL,
    trimester      INTEGER NOT NULL DEFAULT 1,
    annee_scolaire VARCHAR(255),
    graded_on      DATE,
    deleted        BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_grade_school ON grade(school_id);

-- 7) Les paiements
CREATE TABLE IF NOT EXISTS payment (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id      BIGINT NOT NULL REFERENCES schools(id),
    student_id     BIGINT NOT NULL REFERENCES student(id),
    amount         NUMERIC(12,2),
    method         VARCHAR(255),               -- CASH, TRANSFER, MOBILE_MONEY
    paid_at        DATE,
    annee_scolaire VARCHAR(255),
    receipt_number VARCHAR(255),
    deleted        BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_payment_receipt UNIQUE (school_id, receipt_number)   -- unique PAR ÉCOLE (règle n°6)
);
CREATE INDEX IF NOT EXISTS idx_payment_school ON payment(school_id);

-- 8) Les messages
CREATE TABLE IF NOT EXISTS app_message (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id           BIGINT NOT NULL REFERENCES schools(id),
    sender_id           BIGINT NOT NULL REFERENCES app_user(id),
    recipient_id        BIGINT NOT NULL REFERENCES app_user(id),
    subject             VARCHAR(255),
    body                VARCHAR(4000),
    link_url            VARCHAR(255),
    link_label          VARCHAR(255),
    sent_at             TIMESTAMP,
    draft               BOOLEAN NOT NULL DEFAULT FALSE,
    read_by_recipient   BOOLEAN NOT NULL DEFAULT FALSE,
    hidden_by_recipient BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_message_school ON app_message(school_id);

-- 9) Le journal (school_id vide = action du propriétaire)
CREATE TABLE IF NOT EXISTS audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id   BIGINT REFERENCES schools(id),
    username    VARCHAR(255),
    action      VARCHAR(255),
    entity      VARCHAR(255),
    entity_id   BIGINT,
    details     VARCHAR(1000),
    happened_at TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_audit_school ON audit_log(school_id);